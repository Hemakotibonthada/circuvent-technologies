"""
Drawn figures for the architecture deck, and a raster cache for real artwork.

WHY DRAW RATHER THAN DESCRIBE

The architecture deck was tables and prose, and both are the wrong shape for the
questions it answers. "What talks to what" is a picture. "Which certificate is
ours" is a picture. "Why does the flat stop working when the router dies" is
very much a picture, and three bullet points about Wi-Fi channels do not land
the way two rows of boxes on different channels do.

Everything here is vector, built from the same shape helpers as the rest of the
company's decks, so it stays crisp at any zoom and matches the palette in
`src/app/globals.css` rather than being screenshots that go stale.

WHY THE RASTERISER EXISTS

python-pptx will not embed an SVG, and every piece of product artwork in this
repository is one — generated by `scripts/gen-product-art.js`, which is the
single owner of what a device looks like. Rather than keep a second set of
hand-exported PNGs that would drift from it, the SVGs are rasterised at build
time into `Docs/kt/_assets/` and embedded from there.

That directory is a build artifact. It is derived from public/img and can be
deleted at any time; the next build puts it back.
"""

from __future__ import annotations

from pathlib import Path

from pptx.util import Inches, Pt
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN

from business_docs.brand import (
    CYAN, CYAN_BRIGHT, VIOLET, INK, INK_DEEP, SLATE, MUTED, PAPER, PAPER_ALT,
)
from business_docs.decks import W, H, _text, _rect, _rgb

ROOT = Path(__file__).resolve().parent.parent.parent
ASSETS = ROOT / "Docs" / "kt" / "_assets"


# --------------------------------------------------------------------------
# Raster cache
# --------------------------------------------------------------------------

def svg_png(name: str, scale: int = 2) -> Path | None:
    """
    Rasterise `public/img/<name>.svg` once and return the PNG.

    Returns None rather than raising when the source is missing or the renderer
    cannot read it: a deck that fails to build because one illustration moved is
    worse than a deck with one illustration missing, and the verifier checks
    that the pictures arrived rather than trusting this to have worked.
    """
    src = ROOT / "public" / "img" / f"{name}.svg"
    if not src.is_file():
        return None
    ASSETS.mkdir(parents=True, exist_ok=True)
    out = ASSETS / f"{name}.png"
    if out.is_file() and out.stat().st_mtime >= src.stat().st_mtime:
        return out
    try:
        import fitz  # PyMuPDF, already used by the document verifiers
        with fitz.open(str(src)) as doc:
            pix = doc[0].get_pixmap(matrix=fitz.Matrix(scale, scale), alpha=False)
            pix.save(str(out))
        return out
    except Exception:
        return None


def picture(slide, name: str, left: float, top: float, width: float) -> bool:
    """Place a rasterised SVG. False when the artwork could not be produced."""
    png = svg_png(name)
    if not png:
        return False
    slide.shapes.add_picture(str(png), Inches(left), Inches(top), width=Inches(width))
    return True



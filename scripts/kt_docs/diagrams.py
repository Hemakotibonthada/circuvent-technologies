def node(slide, left, top, width, height, title, sub="", *,
         fill=PAPER_ALT, accent=CYAN, title_color=INK, sub_color=MUTED,
         title_size=11.5, sub_size=8.5):
    """A labelled box with an accent edge. The unit every diagram is built from."""
    _rect(slide, left, top, width, height, fill)
    _rect(slide, left, top, width, 0.045, accent)
    _text(slide, left + 0.1, top + 0.16, width - 0.2, 0.32, title,
          size=title_size, bold=True, color=title_color)
    if sub:
        _text(slide, left + 0.1, top + 0.5, width - 0.2, height - 0.58, sub,
              size=sub_size, color=sub_color)


def connector(slide, x1, y1, x2, y2, *, color=CYAN, width=1.5, dashed=False):
    """
    A straight line between two points, in inches.

    Drawn with a connector shape rather than a thin rectangle so it survives
    being moved in PowerPoint by whoever edits the deck next — a rectangle
    rotated to look like a diagonal stops being a line the moment anything
    around it is nudged.
    """
    from pptx.util import Emu
    conn = slide.shapes.add_connector(
        1,  # straight
        Inches(x1), Inches(y1), Inches(x2), Inches(y2),
    )
    conn.line.color.rgb = _rgb(color)
    conn.line.width = Pt(width)
    if dashed:
        from pptx.enum.dml import MSO_LINE_DASH_STYLE
        conn.line.dash_style = MSO_LINE_DASH_STYLE.DASH
    return conn


def chip(slide, left, top, width, text, *, fill=CYAN, color=PAPER, size=8.5):
    """A small pill used to label a connection."""
    _rect(slide, left, top, width, 0.26, fill, radius=True)
    _text(slide, left, top + 0.03, width, 0.22, text, size=size, bold=True,
          color=color, align=PP_ALIGN.CENTER)


